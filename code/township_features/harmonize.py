import csv,re
MERGE={'臺北縣':'新北市','臺中縣':'臺中市','臺南縣':'臺南市','高雄縣':'高雄市','桃園縣':'桃園市'}
SPECIAL={('臺南市','中區'):('臺南市','中西區'),('臺南市','西區'):('臺南市','中西區'),('高雄縣','三民鄉'):('高雄市','那瑪夏區'),
         ('苗栗縣','頭份鎮'):('苗栗縣','頭份市'),('彰化縣','員林鎮'):('彰化縣','員林市'),('臺東縣','臺東市'):('臺東縣','臺東市')}
def cur(c,t,y):
    if (c,t) in SPECIAL and not (c=='臺南市' and y>=99): return SPECIAL[(c,t)]
    if c in MERGE: return MERGE[c], re.sub(r'[鄉鎮市]$','區',t)
    if c=='桃園市': return c, re.sub(r'[鄉鎮市]$','區',t)
    return c,t
